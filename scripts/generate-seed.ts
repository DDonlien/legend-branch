import { writeFile } from "node:fs/promises";
import { KnowledgeStore } from "../server/store";
import { seed } from "../server/seed";
import type { Database, Statement } from "../server/model";

class MigrationStatement implements Statement {
  constructor(readonly sql: string, readonly values: (string | number | null)[] = []) {}
  bind(...values: (string | number | null)[]) { return new MigrationStatement(this.sql, values); }
  async all<T>() { return { results: [] as T[] }; }
  async first<T>() { return null as T | null; }
  serialize() {
    let i = 0;
    return this.sql.replace(/\?/g, () => {
      const value = this.values[i++];
      return value === null ? "NULL" : typeof value === "number" ? String(value) : `'${value.replace(/'/g, "''")}'`;
    }) + ";";
  }
}
let migration = "-- Generated by npm run seed:generate from src/data.ts and server/seed.ts.\n";
const database: Database = {
  prepare: (sql) => new MigrationStatement(sql),
  async batch(statements) {
    migration += statements.map((stmt) => (stmt as MigrationStatement).serialize()).join("\n");
    return statements.map(() => ({ meta: { changes: 0 } }));
  },
};
await new KnowledgeStore(database).merge(seed, "2026-10-10T00:00:00.000Z");
// Export for review; never rewrite an already-applied database migration.
await writeFile(new URL("../output/generated-seed.sql", import.meta.url), migration + "\n");
